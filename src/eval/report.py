"""Turn the raw evaluation record into a Markdown comparison report.

Run:  python -m src.eval.report

Reads results/eval_raw.json and writes results/evaluation.md. Separated from the
runner so the report can be regenerated without re-running retrieval.

The report is written to be read by someone who did not build the system, so it
states what each number means and what it does not. In particular it reports
both file-level and section-level Hit@k, and treats a gap between the two as a
finding rather than an inconvenience.
"""

from __future__ import annotations

import sys
from collections.abc import Sequence

from src.eval.analyze import rank_changes
from src.eval.metrics import (
    DEFAULT_K_VALUES,
    MatchLevel,
    MetricSummary,
    QuestionResult,
    compare_retrievers,
    summarize,
)
from src.eval.questions import CATEGORIES, load_questions
from src.eval.runner import RESULTS_DIR, load_raw

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

RETRIEVER_ORDER = ("bm25", "dense", "hybrid")
RETRIEVER_LABELS = {
    "bm25": "BM25 only",
    "dense": "Dense only",
    "hybrid": "Hybrid (RRF)",
}

# On 55 answerable questions, one question is worth 1.8 percentage points. A
# gap smaller than that is a single question changing rank, which is noise, not
# a result — so the report says so rather than declaring a winner.
ONE_QUESTION = 1.0 / 55


def _pct(value: float) -> str:
    return f"{value:.3f}"


def _table(
    summaries: Sequence[MetricSummary], k_values: Sequence[int] = DEFAULT_K_VALUES
) -> list[str]:
    header = "| Retriever | " + " | ".join(f"Hit@{k}" for k in k_values) + " | MRR |"
    divider = "|---|" + "---|" * (len(k_values) + 1)
    rows = [header, divider]
    for summary in summaries:
        cells = [_pct(summary.hits.get(k, 0.0)) for k in k_values]
        label = RETRIEVER_LABELS.get(summary.retriever, summary.retriever)
        rows.append(f"| {label} | " + " | ".join(cells) + f" | {_pct(summary.mrr)} |")
    return rows


def _summaries(
    results: dict[str, list[QuestionResult]],
    level: str,
    category: str | None = None,
) -> list[MetricSummary]:
    return [
        summarize(results[name], retriever=name, level=level, category=category)
        for name in RETRIEVER_ORDER
        if name in results
    ]


def _verdict(summaries: Sequence[MetricSummary], metric: str = "mrr") -> str:
    """State the winner, or state plainly that the difference is not real."""
    winner, margin = compare_retrievers(summaries, metric=metric)
    if margin < ONE_QUESTION:
        return (
            f"`{RETRIEVER_LABELS.get(winner, winner)}` leads on {metric}, but by "
            f"{margin:.3f} — less than one question is worth ({ONE_QUESTION:.3f}). "
            f"That is not a difference."
        )
    return (
        f"`{RETRIEVER_LABELS.get(winner, winner)}` wins on {metric} by {margin:.3f}, "
        f"about {margin / ONE_QUESTION:.1f} questions' worth."
    )


def build_report(
    raw: dict[str, dict[str, list[QuestionResult]]],
) -> str:
    questions = load_questions()
    answerable = sum(q.answerable for q in questions)
    lines: list[str] = []
    add = lines.append

    add("# Retrieval evaluation")
    add("")
    add(
        f"{len(questions)} labeled questions over the PostgreSQL 17.0 documentation, "
        f"{answerable} of them answerable. Generated by `make eval`; the raw "
        f"per-question record is in `results/eval_raw.json`."
    )
    add("")

    # --- how to read it ----------------------------------------------------
    add("## How to read these numbers")
    add("")
    add(
        "**Hit@k** — did a correct passage appear in the top *k* results? "
        "It is a yes/no per question, averaged over the set."
    )
    add("")
    add(
        "**MRR** — mean reciprocal rank. Each question scores `1/rank` of its "
        "first correct result, so rank 1 scores 1.00 and rank 5 scores 0.20. "
        "Hit@k cannot tell rank 1 from rank 3; MRR can."
    )
    add("")
    add(
        "**Two levels.** All 374 configuration parameters live in one "
        "54,000-token `config.sgml`, and 23 of the 55 answerable questions "
        "point at it. *File-level* counts a hit as soon as any chunk from the "
        "right file appears — including one about locale settings. "
        "*Section-level* asks whether the right passage was found. The gap "
        "between them is a measure of how much the file-level number flatters."
    )
    add("")
    add(
        "Only answerable questions are scored. The 15 unanswerable ones have no "
        "gold passage, so every retriever scores zero on them; including them "
        "would move all three numbers by the same amount and tell you nothing. "
        "Abstention is measured in Phase 6, where it belongs."
    )
    add("")
    add(
        f"On {answerable} questions, one question is worth {ONE_QUESTION:.3f}. "
        f"A gap smaller than that is one question changing rank, not a finding."
    )
    add("")

    structural = raw.get("structural", {})

    # --- the main table ----------------------------------------------------
    add("## The three-way comparison")
    add("")
    add("Structure-aware chunking, section-level scoring — the headline numbers.")
    add("")
    section_summaries = _summaries(structural, MatchLevel.SECTION)
    lines.extend(_table(section_summaries))
    add("")
    add(_verdict(section_summaries))
    add("")

    add("### Same run, scored at file level")
    add("")
    file_summaries = _summaries(structural, MatchLevel.FILE)
    lines.extend(_table(file_summaries))
    add("")
    add(_verdict(file_summaries))
    add("")

    # The divergence between levels, stated as its own observation.
    for section, file_ in zip(section_summaries, file_summaries, strict=True):
        gap = file_.hits.get(3, 0.0) - section.hits.get(3, 0.0)
        label = RETRIEVER_LABELS.get(section.retriever, section.retriever)
        add(
            f"- **{label}**: Hit@3 is {_pct(file_.hits.get(3, 0.0))} at file level "
            f"but {_pct(section.hits.get(3, 0.0))} at section level — a gap of "
            f"{gap:.3f}. That gap is how often it found the right document and "
            f"the wrong passage inside it."
        )
    add("")

    # --- per category ------------------------------------------------------
    add("## Per-category breakdown")
    add("")
    add(
        "Where each retriever wins is more interesting than which wins overall. "
        "BM25 matches strings; dense retrieval matches meaning. The categories "
        "are built to separate those."
    )
    add("")

    for category in CATEGORIES:
        if category == "unanswerable":
            continue
        summaries = _summaries(structural, MatchLevel.SECTION, category=category)
        if not summaries or summaries[0].n_questions == 0:
            continue
        add(f"### {category} ({summaries[0].n_questions} questions)")
        add("")
        lines.extend(_table(summaries))
        add("")
        add(_verdict(summaries))
        add("")

    # --- chunking ablation -------------------------------------------------
    if "fixed" in raw:
        add("## Chunking ablation")
        add("")
        add(
            "The same retrievers over fixed-size chunks, which ignore document "
            "structure entirely. This is what justifies Phase 2's complexity — "
            "or fails to."
        )
        add("")
        add(
            "**Only file-level scoring is comparable here.** A fixed chunk has "
            "no heading path — that is the definition of fixed chunking — so "
            "section-level scoring is not a contest it loses, it is a "
            "measurement that does not exist for it. Reporting the structural "
            "section-level MRR against a mechanical zero would be a fabricated "
            "landslide."
        )
        add("")
        add("| Retriever | Structural MRR | Fixed MRR | Delta |")
        add("|---|---|---|---|")
        deltas: list[tuple[str, float]] = []
        for name in RETRIEVER_ORDER:
            if name not in structural or name not in raw["fixed"]:
                continue
            s = summarize(structural[name], retriever=name, level=MatchLevel.FILE)
            f = summarize(raw["fixed"][name], retriever=name, level=MatchLevel.FILE)
            delta = s.mrr - f.mrr
            deltas.append((name, delta))
            add(
                f"| {RETRIEVER_LABELS.get(name, name)} | {_pct(s.mrr)} | "
                f"{_pct(f.mrr)} | {delta:+.3f} |"
            )
        add("")

        real = [(n, d) for n, d in deltas if abs(d) >= ONE_QUESTION]
        if not real:
            add(
                "Every delta is smaller than one question is worth "
                f"({ONE_QUESTION:.3f}). **At file level, structure-aware "
                "chunking did not measurably beat fixed-size chunking on this "
                "corpus.**"
            )
        else:
            for name, delta in real:
                direction = "ahead of" if delta > 0 else "behind"
                add(
                    f"- {RETRIEVER_LABELS.get(name, name)}: structural is "
                    f"{abs(delta):.3f} {direction} fixed, about "
                    f"{abs(delta) / ONE_QUESTION:.1f} questions."
                )
        add("")
        add(
            "What structure-aware chunking buys is not visible in this table. "
            "It is the heading path, which is what makes section-level scoring "
            "possible at all — and section level is the measurement that "
            "reflects whether the right *passage* was found rather than the "
            "right file. The ablation shows the two chunkers are close on the "
            "coarse metric; the fine metric only exists for one of them."
        )
        add("")

    # --- the honest finding ------------------------------------------------
    section_by_name = {s.retriever: s for s in section_summaries}
    dense_mrr = section_by_name.get("dense")
    hybrid_mrr = section_by_name.get("hybrid")
    if dense_mrr and hybrid_mrr and dense_mrr.mrr > hybrid_mrr.mrr + ONE_QUESTION:
        add("## Hybrid retrieval did not win, and here is why")
        add("")
        add(
            f"The plan expects RRF fusion to beat either retriever alone. On "
            f"this corpus it does not: dense retrieval scores "
            f"{_pct(dense_mrr.mrr)} on section-level MRR against the hybrid's "
            f"{_pct(hybrid_mrr.mrr)}, a gap of "
            f"{dense_mrr.mrr - hybrid_mrr.mrr:.3f} — about "
            f"{(dense_mrr.mrr - hybrid_mrr.mrr) / ONE_QUESTION:.1f} questions."
        )
        add("")
        add(
            "Reporting that plainly is the point. The mechanism is visible in "
            "the per-question record (`python -m src.eval.analyze`):"
        )
        add("")
        for source in ("bm25", "dense"):
            if source not in structural:
                continue
            improved, degraded = rank_changes(
                structural[source], structural["hybrid"], MatchLevel.SECTION
            )
            net = len(improved) - len(degraded)
            verdict = (
                "a clear net gain"
                if net > 2
                else "**net zero**"
                if net == 0
                else f"net {net:+d}"
            )
            add(
                f"- Against {RETRIEVER_LABELS.get(source, source)}, fusion "
                f"improved {len(improved)} questions and worsened "
                f"{len(degraded)} — {verdict}."
            )
        add("")
        add(
            "RRF cannot invent a good result; it can only reorder what its "
            "inputs give it. When dense retrieval already ranks the gold "
            "passage first and BM25 ranks it tenth, averaging the two ranks "
            "pulls it down. Fusion helps the weaker retriever and costs the "
            "stronger one, and on a corpus where one input is consistently "
            "better, that trade is not worth making."
        )
        add("")
        add(
            "The hybrid still wins at file level and on Hit@3 and Hit@5 at "
            "section level, so it is not strictly worse — it is better at "
            "finding the right area and worse at ranking the exact passage "
            "first. Which matters depends on what is downstream. For Phase 6, "
            "where roughly five chunks are handed to a generator, Hit@5 is "
            "arguably the more relevant number, and there the hybrid leads."
        )
        add("")

    # --- limits ------------------------------------------------------------
    add("## What these numbers do not show")
    add("")
    add(
        "- **Precision.** A retriever returning the gold passage at rank 1 and "
        "noise at 2–5 scores the same as one returning five relevant chunks. "
        "Nothing here penalizes the noise."
    )
    add(
        "- **Abstention.** Every number above is computed over answerable "
        "questions only. Whether the system knows when to say 'I don't know' is "
        "Phase 6."
    )
    add(
        "- **Answer quality.** This measures retrieval, not generation. A "
        "perfect Hit@1 still says nothing about whether the answer built from "
        "that passage is correct."
    )
    add(
        f"- **Sample size.** {answerable} questions. Differences below "
        f"{ONE_QUESTION:.3f} are one question, and the report says so rather "
        f"than reporting them as results."
    )
    add("")

    return "\n".join(lines) + "\n"


def main() -> int:
    raw_path = RESULTS_DIR / "eval_raw.json"
    if not raw_path.exists():
        print(f"No results at {raw_path}.", file=sys.stderr)
        print("Run: python -m src.eval.runner", file=sys.stderr)
        return 1

    raw = load_raw(raw_path)
    report = build_report(raw)

    out_path = RESULTS_DIR / "evaluation.md"
    out_path.write_text(report, encoding="utf-8")

    print(report)
    print(f"\nWrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
